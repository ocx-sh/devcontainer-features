# run-scenarios.sh [name...]: the scenario suite. Names come from test/ocx/scenarios.json (each run
# through `devcontainer features test`, the script test/ocx/<name>.sh), plus `duplicate` (the CLI's
# duplicate test), the `fail-*` negative checks of test/images/failures.json (the build must fail with
# the exact message and exit code) and `up-proof` (a real `devcontainer up`: the lifecycle hook runs
# as the remote user). No name runs everything; JOBS (default 3) run at a time and each runs to
# completion. Ends with one table and exits 1 when any failed.
# Each scenario runs from a staged copy under target/scenarios/<name>/ (one scenario in
# scenarios.json, src/ocx, its script), so a run never sees another's files.
# Reports: target/reports/scenarios/<name>.log, target/reports/junit/scenarios-<name>.xml.
# Run from the repo root inside `ocx exec -g all --` (the test:scenarios task does); needs jq.
# Exit: 0 all passed, 1 a scenario failed, 2 usage.
# shellcheck disable=SC2310,SC2016 # run_locked and judge are tried in conditions on purpose; command text is for the inner shell
set -eu

__OCXF_RUN_IMAGE_SOURCE_ONLY=1
# shellcheck source=run-image.sh
. test/images/run-image.sh

OUT=target/reports
SCN=$OUT/scenarios
JOBS=${JOBS:-3}
case $JOBS in '' | *[!0-9]* | 0) echo "run-scenarios: JOBS must be a positive integer (got: $JOBS)" >&2 && exit 2 ;; esac
JUNIT_KIND=scenarios
export JUNIT_KIND

# json_keys <file>: the top-level keys, one per line.
json_keys() {
    jq -r 'keys_unsorted[]' "$1"
}

all_names() {
    json_keys test/ocx/scenarios.json
    echo duplicate
    json_keys test/images/failures.json
    echo up-proof
}

# image_tag <image>: ocx-test/x:local becomes ocx-test/x:scn-<run id>, a tag only this run owns.
image_tag() {
    case $1 in
        ocx-test/*:local) printf '%s\n' "${1%:local}:scn-$RUN_ID" ;;
        *) printf '%s\n' "$1" ;;
    esac
}

# stage <name> <dir>: a project for `features test -p <dir>` holding just this scenario.
stage() {
    rm -rf "$2"
    mkdir -p "$2/src" "$2/test/ocx"
    cp -R src/ocx "$2/src/ocx"
    cp test/ocx/check.sh test/ocx/scenario.sh "$2/test/ocx/"
    digest=$(awk '{ print $1; exit }' src/ocx/dist.json.sha256)
    case $1 in
        duplicate) cp test/ocx/duplicate.sh "$2/test/ocx/" ;;
        fail-*)
            # the CLI wants a test script even for a scenario whose build is expected to fail
            printf '#!/bin/sh\nexit 0\n' >"$2/test/ocx/$1.sh"
            chmod +x "$2/test/ocx/$1.sh"
            jq -c --arg n "$1" '{($n): {image: .[$n].image, features: {ocx: .[$n].options}}}' test/images/failures.json >"$2/test/ocx/scenarios.json"
            ;;
        *)
            cp "test/ocx/$1.sh" "$2/test/ocx/"
            [ ! -d "test/ocx/$1" ] || cp -R "test/ocx/$1" "$2/test/ocx/$1"
            [ "$1" != reinstall ] || cp -R src/ocx "$2/test/ocx/feature-src"
            printf '%s\n' "$digest" >"$2/test/ocx/dist-digest.expected"
            jq -c --arg n "$1" --arg d "$digest" --arg r "$RUN_ID" '
                {($n): .[$n]} | walk(if type == "string" then gsub("@DIST_DIGEST@"; $d) | gsub("(?<p>ocx-test/[a-z-]+):local"; "\(.p):scn-\($r)") else . end)' \
                test/ocx/scenarios.json >"$2/test/ocx/scenarios.json"
            ;;
    esac
}

# one <name>: run one scenario, write $SCN/<name>.result as `<result> <seconds>`.
one() {
    name=$1
    log=$SCN/$name.log
    stagedir=target/scenarios/$name
    extra=$SCN/$name.extra.xml
    : >"$extra"
    t0=$(date +%s)
    rc=0
    case $name in
        up-proof) up_proof "$log" || rc=$? ;;
        *)
            stage "$name" "$stagedir"
            # shellcheck disable=SC2086 # DC is a command line of several words on purpose
            case $name in
                duplicate) run_locked "$log" $DC features test -p "$stagedir" -f ocx --skip-scenarios --skip-autogenerated --preserve-test-containers -i debian:stable-slim || rc=$? ;;
                *) run_locked "$log" $DC features test -p "$stagedir" -f ocx --skip-autogenerated --skip-duplicated --preserve-test-containers || rc=$? ;;
            esac
            judge || rc=1
            ;;
    esac
    cleanup_run "$log"
    rm -rf "$stagedir"
    junit "$name" "$log" "$rc" "$extra"
    rm -f "$extra"
    secs=$(($(date +%s) - t0))
    if [ "$rc" -eq 0 ]; then res=pass; else res=FAIL; fi
    echo "$res $secs" >"$SCN/$name.result"
    printf 'scenario %-36s %-5s %4ss\n' "$name" "$res" "$secs"
}

# judge: add the checks the CLI cannot express to the log; return 1 when they fail.
# fail-*: the CLI run must fail, with the exit code and the message of failures.json.
# version-latest: the installed version is the newest stable of src/ocx/dist.json.
judge() {
    case $name in
        fail-*)
            want=$(jq -r --arg n "$name" '.[$n] | "\(.exit)\n\(.message)"' test/images/failures.json)
            code=$(printf '%s\n' "$want" | sed -n 1p)
            msg=$(printf '%s\n' "$want" | sed -n 2p)
            bad=0
            if [ "$rc" -ne 0 ] && grep -q "exit code: $code" "$log"; then
                printf 'ok - the build fails with exit code %s\n' "$code" >>"$log"
            else
                printf 'not ok - the build fails with exit code %s (CLI exit %s)\n' "$code" "$rc" >>"$log"
                bad=1
            fi
            if grep -F -q "ocx-feature: error: $msg" "$log"; then
                printf 'ok - the build log says: %s\n' "$msg" >>"$log"
            else
                printf 'not ok - the build log says: %s\n' "$msg" >>"$log"
                bad=1
            fi
            # a failed build is the expected outcome, so the CLI's own exit status no longer counts
            rc=$bad
            return "$bad"
            ;;
        version-latest)
            got=$(sed -n 's/^# ocx-version=//p' "$log" | tail -n 1)
            if [ "$got" = "$(newest_stable)" ]; then
                printf 'ok - installed ocx %s is the newest stable of src/ocx/dist.json\n' "$got" >>"$log"
            else
                printf 'not ok - installed ocx %s is the newest stable of src/ocx/dist.json (%s)\n' "${got:-none}" "$(newest_stable)" >>"$log"
                return 1
            fi
            ;;
    esac
    return "$rc"
}

# up_proof <log>: a real `devcontainer up`; the hook the CLI ran owns the files it made.
up_proof() {
    # shellcheck disable=SC2016 # the command text is for the container's shell
    CMD='id -un; stat -c %U ~/.ocx .ocx/toolchain ocx.lock; command -v jq' sh test/images/run-workspace.sh devcontainers-debian vscode >"$1" 2>&1 || {
        printf 'not ok - devcontainer up and exec succeed\n' >>"$1"
        return 1
    }
    n=$(grep -c '^vscode$' "$1" || true)
    if [ "$n" = 4 ]; then
        printf 'ok - the CLI ran the hook as vscode: ~/.ocx, .ocx/toolchain and ocx.lock are owned by vscode (id -un: vscode)\n' >>"$1"
    else
        printf 'not ok - the CLI ran the hook as vscode (%s of 4 lines say vscode)\n' "$n" >>"$1"
        return 1
    fi
    if grep -q '/\.ocx/toolchain/links/default/jq/content/jq$' "$1"; then
        printf 'ok - a login interactive shell resolves jq from the project toolchain\n' >>"$1"
    else
        printf 'not ok - a login interactive shell resolves jq from the project toolchain\n' >>"$1"
        return 1
    fi
}

if [ "${1:-}" = --one ]; then
    RUN_ID=$2
    one "$3"
    exit 0
fi

mkdir -p "$SCN" "$OUT/junit"
names=$*
[ -n "$names" ] || names=$(all_names)
known=$(all_names)
for n in $names; do
    printf '%s\n' "$known" | grep -q -x -F -- "$n" || {
        echo "run-scenarios: unknown scenario '$n'; known: $(echo "$known" | tr '\n' ' ')" >&2
        exit 2
    }
done

RUN_ID=$$
built=
cleanup_all() {
    for b in $built; do docker rmi -f "$b" >/dev/null 2>&1 || :; done
    rm -rf target/scenarios
    rmdir target/run 2>/dev/null || :
}
trap cleanup_all EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# Local base images (ocx-test/*) of the selected scenarios, built once under a tag only this run owns.
for n in $names; do
    case $n in fail-* | duplicate | up-proof) continue ;; esac
    img=$(jq -r --arg n "$n" '.[$n].image' test/ocx/scenarios.json)
    case $img in
        ocx-test/*:local)
            tag=$(image_tag "$img")
            case " $built " in *" $tag "*) continue ;; esac
            echo "building $tag from test/images/$(basename "${img%%:*}")"
            docker build -q -t "$tag" "test/images/$(basename "${img%%:*}")" >/dev/null
            built="$built $tag"
            ;;
    esac
done

rm -f "$SCN"/*.result
echo "scenarios: $(echo "$names" | wc -w | tr -d ' ') selected, $JOBS at a time"
# shellcheck disable=SC2086 # names are single words
printf '%s\n' $names | xargs -P "$JOBS" -I{} sh test/images/run-scenarios.sh --one "$RUN_ID" {}

echo
printf '%-36s | %-6s | %s\n' scenario result seconds
printf '%-36s-+-%-6s-+-%s\n' ------------------------------------ ------ -------
failed=
for n in $names; do
    read -r res secs <"$SCN/$n.result" || {
        res=FAIL
        secs=0
    }
    printf '%-36s | %-6s | %s\n' "$n" "$res" "$secs"
    [ "$res" != FAIL ] || failed="$failed $n"
done
if [ -n "$failed" ]; then
    echo
    echo "failed:$failed"
    for n in $failed; do
        echo "  task test:scenarios SCENARIO=$n   (log: $SCN/$n.log)"
        grep -A8 '^not ok - ' "$SCN/$n.log" 2>/dev/null | head -n 20 || :
    done
    exit 1
fi
